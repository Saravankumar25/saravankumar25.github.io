#!/usr/bin/env node
// Generates chapters/99-sources-and-limitations/02.html: every official page and screenshot actually used by the chapters.
// Run after the chapters are written: node tools/tdm-guide/cited-sources.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const chapDir = path.join(here, "chapters");
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const groups = {
  "Delphix Continuous Compliance docs": (u) => u.startsWith("https://help.delphix.com/"),
  "GenRocket help centre and app": (u) => /^https:\/\/(genrocket\.helpjuice\.com|app\.genrocket\.com)\//.test(u),
  "Other official or supplied links": (u) => !u.startsWith("https://help.delphix.com/") && !/genrocket|helpjuice/.test(u) && !u.startsWith("https://saravankumar25.github.io"),
};
const pages = {}; // url -> Set(chapter nums)
const shots = {}; // chapter -> count
const titles = {};
for (const d of fs.readdirSync(chapDir).sort()) {
  const dir = path.join(chapDir, d);
  if (!fs.statSync(dir).isDirectory() || d.startsWith("99")) continue;
  const meta = JSON.parse(fs.readFileSync(path.join(dir, "meta.json"), "utf8"));
  titles[meta.num] = meta.title;
  const html = fs.readdirSync(dir).filter((f) => f.endsWith(".html")).sort().map((f) => fs.readFileSync(path.join(dir, f), "utf8")).join("\n");
  shots[meta.num] = (html.match(/<figure class="shot"/g) || []).length;
  for (const m of html.matchAll(/<a [^>]*href="(https?:\/\/[^"#]+)[^"]*"[^>]*>/g)) {
    const u = m[1];
    if (/\.(png|jpe?g|gif|svg|webp)(\?|$)/i.test(u) || /helpjuice\.com\/helpjuice_production\//.test(u) || /\/resources\/images\//.test(u)) continue; // screenshot links
    (pages[u] ||= new Set()).add(meta.num);
  }
}
let out = `<h2 id="c99-cited">99.5 Every official page used, by chapter</h2>\n<p>This list is generated by script from the finished chapters, so it always matches what the chapters link to. Screenshot links are not repeated here; each appears beside the step it illustrates.</p>\n`;
const total = Object.values(shots).reduce((a, b) => a + b, 0);
out += `<p><strong>${total}</strong> official screenshots are embedded across the guide:</p>\n<div class="tablewrap"><table><thead><tr><th>Chapter</th><th>Embedded official screenshots</th></tr></thead><tbody>\n`;
for (const n of Object.keys(shots).map(Number).sort((a, b) => a - b)) if (shots[n]) out += `<tr><td><a href="${String(n).padStart(2, "0")}-${fs.readdirSync(chapDir).find((d) => d.startsWith(String(n).padStart(2, "0") + "-")).slice(3)}.html">${n}. ${esc(titles[n])}</a></td><td>${shots[n]}</td></tr>\n`;
out += `</tbody></table></div>\n`;
for (const [name, test] of Object.entries(groups)) {
  const urls = Object.keys(pages).filter(test).sort();
  if (!urls.length) continue;
  out += `<h3 id="c99-cited-${name.toLowerCase().replace(/[^a-z]+/g, "-")}">${esc(name)} (${urls.length})</h3>\n<ul>\n`;
  for (const u of urls) out += `<li><a href="${u}" target="_blank" rel="noopener">${esc(u.replace(/^https:\/\//, ""))}</a> · chapters ${[...pages[u]].sort((a, b) => a - b).join(", ")}</li>\n`;
  out += `</ul>\n`;
}
fs.writeFileSync(path.join(chapDir, "99-sources-and-limitations", "02.html"), out);
console.log(`cited pages: ${Object.keys(pages).length}, screenshots: ${total}`);
